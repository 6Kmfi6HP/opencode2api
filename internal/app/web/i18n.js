(function () {
  "use strict";
  var LANG_STORAGE_KEY = "admin_lang";

  function normalizeLang(lang) {
    return /^en/i.test(String(lang || "")) ? "en" : "zh";
  }

  // Resolution order: URL ?lang= -> localStorage("admin_lang") -> navigator.language.
  function resolveLang() {
    try {
      var qs = new URLSearchParams(window.location.search).get("lang");
      if (qs) return normalizeLang(qs);
    } catch (e) {}
    try {
      var saved = window.localStorage.getItem(LANG_STORAGE_KEY);
      if (saved) return normalizeLang(saved);
    } catch (e) {}
    return normalizeLang(navigator.language);
  }

  function interpolate(text, params) {
    if (!params) return text;
    return String(text).replace(/\{(\w+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match;
    });
  }

  // t(key, params) resolves the key in the active language, falls back to
  // zh, then to the key itself; {name} placeholders are substituted from params.
  window.t = function (key, params) {
    var dict = window.I18N_DICT || {};
    var lang = resolveLang();
    var value = (dict[lang] && dict[lang][key]);
    if (value === undefined || value === null) value = (dict.zh && dict.zh[key]);
    if (value === undefined || value === null) value = key;
    return interpolate(value, params);
  };

  // I18N_apply() fills every element keyed via data-i18n (textContent),
  // data-i18n-placeholder (placeholder) and data-i18n-title (title).
  window.I18N_apply = function () {
    var lang = resolveLang();
    var nodes = document.querySelectorAll("[data-i18n], [data-i18n-placeholder], [data-i18n-title]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute("data-i18n");
      if (key) el.textContent = window.t(key);
      key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", window.t(key));
      key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", window.t(key));
    }
    document.documentElement.lang = lang;
  };

  // I18N_setLang(lang) persists the choice and reloads so static markup and
  // server-rendered content pick up the new language.
  window.I18N_setLang = function (lang) {
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, normalizeLang(lang));
    } catch (e) {}
    window.location.reload();
  };

  // Auto-apply once the DOM is ready (the script tag sits at the end of
  // body, but DOMContentLoaded is the safe fallback).
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      window.I18N_apply();
    });
  } else {
    window.I18N_apply();
  }
})();
